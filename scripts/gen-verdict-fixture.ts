// `pnpm test:crosscheck` step 1 (docs/SPEC.md §5): sign a verdict in TypeScript with the shared helpers and
// write contracts/test/fixtures/verdict.json for contracts/test/VerdictCrossCheck.t.sol.
//
// The vault address is deterministic: a fixed deployer creates the vault at nonce 0, then the test token
// (nonce 1) and the test target (nonce 2). Solidity recomputes the same addresses with vm.computeCreateAddress.
// Every key and address here is a throwaway test value; nothing is funded.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  encodeAbiParameters,
  encodeFunctionData,
  erc20Abi,
  getContractAddress,
  hashTypedData,
  keccak256,
  parseAbi,
  toHex,
  type Address,
} from "viem";
import { privateKeyToAccount } from "viem/accounts";
import {
  CALL_TUPLE,
  FUJI_CHAIN_ID,
  hashCalls,
  recoverVerdictSigner,
  verdictDomain,
  verdictTypes,
  type Call,
  type VerdictMessage,
} from "@guardian402/shared";
import { signVerdict } from "@guardian402/shared/sign";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "../contracts/test/fixtures/verdict.json");

const guardian = privateKeyToAccount(keccak256(toHex("guardian402 crosscheck guardian")));
const deployer = privateKeyToAccount(keccak256(toHex("guardian402 crosscheck deployer"))).address;
const owner = privateKeyToAccount(keccak256(toHex("guardian402 crosscheck owner"))).address;
const agent = privateKeyToAccount(keccak256(toHex("guardian402 crosscheck agent"))).address;

const at = (nonce: bigint): Address => getContractAddress({ from: deployer, nonce });
const vault = at(0n);
const token = at(1n); // MockUSDC, 6 decimals
const target = at(2n); // MockTarget

const targetAbi = parseAbi([
  "function pull(address token, uint256 amount)",
  "function ping(uint256 x) payable",
]);
const calls: Call[] = [
  {
    target: token,
    value: 0n,
    data: encodeFunctionData({ abi: erc20Abi, functionName: "approve", args: [target, 2_000_000n] }),
  },
  {
    target,
    value: 0n,
    data: encodeFunctionData({ abi: targetAbi, functionName: "pull", args: [token, 2_000_000n] }),
  },
  { target, value: 1000n, data: encodeFunctionData({ abi: targetAbi, functionName: "ping", args: [7n] }) },
];

const timestamp = 1_900_000_000;
const verdict: VerdictMessage = {
  callsHash: hashCalls(calls),
  nonce: 0n,
  deadline: 2_000_000_000n,
  risk: 0,
  checkId: keccak256(toHex("guardian402 crosscheck check 1")),
};
const signature = await signVerdict({ account: guardian, vault, chainId: FUJI_CHAIN_ID, verdict });
const digest = hashTypedData({
  domain: verdictDomain(vault, FUJI_CHAIN_ID),
  types: verdictTypes,
  primaryType: "Verdict",
  message: verdict,
});
if (
  (await recoverVerdictSigner({ vault, chainId: FUJI_CHAIN_ID, verdict, signature })) !== guardian.address
) {
  throw new Error("signature does not recover to the guardian");
}

const fixture = {
  description: "Generated by scripts/gen-verdict-fixture.ts (pnpm test:crosscheck). Test values only.",
  chainId: FUJI_CHAIN_ID,
  timestamp,
  deployer,
  vault,
  token,
  target,
  owner,
  agent,
  signer: guardian.address,
  calls: calls.map((c) => ({ target: c.target, value: c.value.toString(), data: c.data })),
  callsEncoded: encodeAbiParameters([CALL_TUPLE], [calls]),
  verdict: {
    callsHash: verdict.callsHash,
    nonce: Number(verdict.nonce),
    deadline: Number(verdict.deadline),
    risk: verdict.risk,
    checkId: verdict.checkId,
  },
  digest,
  signature,
};
writeFileSync(OUT, `${JSON.stringify(fixture, null, 2)}\n`);
console.log(`[crosscheck] wrote ${OUT}`);
console.log(`[crosscheck] vault ${vault} signer ${guardian.address} callsHash ${verdict.callsHash}`);
